// Renderer-backed alias-quality instrument and baseline (Plan B Task 2).
//
// Why the real renderer: for a multirate nonlinear stage the quality selector
// normally lives in the plug-in wrapper, so a DSP-core unit test cannot
// establish a *quality ordering*. See
// audio-knowledge/validation/renderer-quality-order-gate.md. This file measures
// folded-harmonic alias energy in audio that has passed through the actual
// HybridWavetableAudioProcessor, via the same OfflineRenderer the rest of the
// suite uses.
//
// The proxy: a single probe tone is played, and the metric compares the energy
// in a narrow band around the tone against the energy where the tone's third
// harmonic folds (|3*f0 - 48000| Hz). A linear path cannot put energy there, so
// whatever appears is generated by a nonlinearity and folded back by sampling.
// Relative to the tone, more-negative dB is cleaner.
//
// Why a band and not measureInharmonicAliasDbc: that metric marks +/-1.5 FFT
// bins around each expected harmonic as "legal", so it only works when the
// probe tone sits on an exact FFT bin. It cannot, here: every float parameter in
// this plug-in is quantised to a 0.01 step, because JUCE 8's
// AudioParameterFloat(id, name, min, max, default) constructor forwards to
// NormalisableRange(min, max, 0.01f). For osc1Tune (+/-24 semitones) that is a
// 1 cent grid, and 1 cent at 10 kHz is 5.8 Hz -- wider than the 2.93 Hz bin
// spacing of the 16384-point analysis. A tone that is 0.4 cents off leaks its
// Hann main lobe outside the legal bins and the metric reads -8.7 dBc of pure
// window leakage no matter how clean the audio is (measured during Task 2).
// Measuring a band 1.4 kHz away from any harmonic removes that dependence.
//
// What this file guarantees:
//   1. the renderer hits the requested pitch to better than 0.1 cent, and a
//      0.005 semitone tune change reaches the audio as 0.5 cent;
//   2. the renderer is deterministic (same seed and configuration, same samples);
//   3. the instrument measures what it claims: a line injected at the folded
//      frequency is reported within 1 dB from -40 down to -120 dBc, so the
//      ceiling gate below cannot pass vacuously; and
//   4. the saturation stage leaves no folded-harmonic energy above the ceiling
//      at either the default or the maximum drive.
//
// The quality-tier gate deliberately does not claim Eco < Normal < High on this
// proxy. Task 3b measured all tiers at the render floor at 10 kHz, while an
// exploratory 13 kHz probe differed by less than 2 dB without a monotonic trend.
// It instead proves that every tier clears the absolute ceiling and that the
// selector changes the rendered signal.

// History worth keeping: this file originally proved its own sensitivity by
// driving the real saturation stage harder and requiring a 15 dB increase in
// folded energy. That worked while the stage was a naive tanh behind a JUCE IIR
// oversampler (-108.9 dBc at full drive). After Plan B Task 3 replaced it with
// antiderivative anti-aliasing plus a half-band FIR, both drive settings land on
// the render's own float32 noise floor (about -152 dBc) and the drive knob can
// no longer move the number. The gate was replaced by an injected-line
// calibration, which tests the instrument directly instead of relying on the
// product being dirty.

